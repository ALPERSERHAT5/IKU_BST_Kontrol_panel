// Tarih formatı
export function formatDate(d) {
  if (!d) return '-';
  const dt = new Date(d);
  const day = String(dt.getDate()).padStart(2, '0');
  const month = String(dt.getMonth() + 1).padStart(2, '0');
  const year = dt.getFullYear();
  const hh = String(dt.getHours()).padStart(2, '0');
  const mm = String(dt.getMinutes()).padStart(2, '0');
  return `${day}.${month}.${year} ${hh}:${mm}`;
}

export function formatDateShort(d) {
  if (!d) return '-';
  const dt = new Date(d);
  const day = String(dt.getDate()).padStart(2, '0');
  const month = String(dt.getMonth() + 1).padStart(2, '0');
  const year = dt.getFullYear();
  return `${day}.${month}.${year}`;
}

// Güvenli HTML escape
export function esc(s) {
  if (s == null) return '';
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// Modal oluştur
export function openModal({ title, body, onClose }) {
  const backdrop = document.createElement('div');
  backdrop.className = 'modal-backdrop';
  backdrop.innerHTML = `
    <div class="modal">
      <div class="modal-head">
        <h2>${esc(title)}</h2>
        <button class="modal-close" type="button">${icons.close}</button>
      </div>
      <div class="modal-body"></div>
    </div>
  `;
  backdrop.querySelector('.modal-body').appendChild(body);
  document.body.appendChild(backdrop);

  const close = () => {
    backdrop.remove();
    if (onClose) onClose();
  };
  backdrop.querySelector('.modal-close').addEventListener('click', close);
  backdrop.addEventListener('click', (e) => {
    if (e.target === backdrop) close();
  });
  return { close, root: backdrop };
}

// Kullanıcıya bildirim (basit toast)
export function toast(msg, type = 'info') {
  const el = document.createElement('div');
  el.className = `alert alert-${type === 'error' ? 'error' : type === 'success' ? 'success' : 'info'}`;
  el.style.position = 'fixed';
  el.style.top = '20px';
  el.style.right = '20px';
  el.style.zIndex = '999';
  el.style.maxWidth = '360px';
  el.style.boxShadow = '0 4px 12px rgba(0,0,0,0.12)';
  el.textContent = msg;
  document.body.appendChild(el);
  setTimeout(() => el.remove(), 3500);
}